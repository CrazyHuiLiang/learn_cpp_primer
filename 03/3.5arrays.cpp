// ===========================================================================
//  《C++ Primer》3.5 节示例：内置数组
// ---------------------------------------------------------------------------
//  数组(array) 是与 C 语言兼容的低级复合类型，大小固定、不可变长。
//  形式：
//      类型 名字[维度];          维度必须是「编译期常量表达式」
//
//  本程序演示：
//    1. 数组的定义与初始化（列表初始化、字符数组与字符串字面值）
//    2. 下标访问元素
//    3. 用 std::begin()/std::end() 获取首/尾指针，安全地用指针遍历数组
//    4. 指针与数组的关系：数组名在很多场合会「退化为」指向首元素的指针
//
//  数组与指针的关系（重要）：
//    - 在多数表达式中，「数组名」会自动转换为「指向首元素的指针」
//      （这叫 decay，退化）。
//    - 因此 int a[5]; auto p = a;  时 p 是 int*，指向 a[0]。
//    - std::begin(a) 返回指向 a[0] 的指针；std::end(a) 返回「尾后指针」，
//      二者配合即可像迭代器一样遍历数组，避免手算元素个数出错。
//
//  注意：现代 C++ 优先用 std::array 或 std::vector，而非内置数组。
//        这里只是为学习底层机制而演示。
// ===========================================================================
#include <iostream>
#include <iterator>      // std::begin / std::end
#include <cstddef>       // std::size_t

int main()
{
    // ---- 1. 数组的定义与初始化 ----
    const std::size_t sz = 5;            // 维度必须是编译期常量
    int ia[sz] = {1, 2, 3, 4, 5};        // 列表初始化，全列出来
    int ib[5] = {1, 2};                  // 前两个为 1、2，其余自动为 0
    int ic[5] = {};                      // 全部初始化为 0
    char ca[6] = "hello";                // 字符数组用字符串字面值初始化
                                         // 注意："hello" 含末尾 '\0'，共 6 个字符，
                                         //       所以 ca 的维度至少要是 6

    // ---- 2. 下标访问 ----
    std::cout << "ia = ";
    for (std::size_t i = 0; i < sz; ++i) {
        std::cout << ia[i] << ' ';
    }
    std::cout << "\n";

    std::cout << "ib = ";
    for (std::size_t i = 0; i < 5; ++i) {
        std::cout << ib[i] << ' ';       // 1 2 0 0 0
    }
    std::cout << "\n";

    std::cout << "ic = ";
    for (std::size_t i = 0; i < 5; ++i) {
        std::cout << ic[i] << ' ';       // 0 0 0 0 0
    }
    std::cout << "\n";

    std::cout << "ca = " << ca << "\n";  // 输出字符数组（按 C 字符串打印）

    // ---- 3. std::begin / std::end + 指针遍历 ----
    // 这两个函数返回「指向首元素」和「尾后」的指针，
    // 让我们能像用迭代器一样安全遍历数组，不必手算长度
    int *pbegin = std::begin(ia);        // 指向 ia[0]
    int *pend   = std::end(ia);          // 指向 ia[5]（尾后，不可解引用）

    std::cout << "用指针遍历 ia：";
    for (int *p = pbegin; p != pend; ++p) {
        std::cout << *p << ' ';
    }
    std::cout << "\n";

    // ---- 4. 指针算术与数组退化 ----
    // 数组名 ia 在表达式中退化为「指向首元素的指针」
    int *p = ia;                         // p 指向 ia[0]
    std::cout << "*p = " << *p
              << ", *(p+2) = " << *(p + 2) << "\n";   // ia[0]=1, ia[2]=3

    // 用指针修改元素
    *p = 100;                            // 等价于 ia[0] = 100
    std::cout << "修改后 ia[0] = " << ia[0] << "\n";

    // 指针相减得到元素个数，类型为 std::ptrdiff_t（有符号）
    std::ptrdiff_t n = std::end(ia) - std::begin(ia);
    std::cout << "ia 的元素个数 = " << n << "\n";

    return 0;
}

// ===========================================================================
//  《C++ Primer》3.2 节示例：string 的读写
// ---------------------------------------------------------------------------
//  string 的两种基本读法：
//    1. std::cin >> s
//         - 直接用 >> 读取：会跳过前导空白（空格、制表、换行），
//           读到「下一个空白」为止，因此一次只读一个「词(word)」。
//         - 读取后空白留在输入流中。
//    2. std::getline(is, s)
//         - 读整行：从流 is 中读取直到遇到换行符，把「这一整行（含中间空白）」
//           存入 s，然后丢弃换行符（不存入 s）。
//         - 适合读取含空格的句子、人名等。
//
//  读取多个值的标准套路：
//    while (std::cin >> word) { ... }      // 读到文件结束或非法输入
//    while (std::getline(std::cin, line)) { ... }   // 逐行读取
//
//  本程序：分别演示「按词读取」和「按行读取」，并把读到的内容原样输出。
// ===========================================================================
#include <iostream>
#include <string>

int main()
{
    // ---------------------------------------------------------------------
    // 一、用 >> 按词读取：跳过前导空白，遇到空白结束
    // ---------------------------------------------------------------------
    // 这里约定读到哨兵词 "end" 就结束本轮演示（也可以用 Ctrl+Z/Ctrl+D 触发 EOF）。
    // 用哨兵的好处是：流中还有后续数据可供下面的 getline 继续读取，
    // 便于在一次运行中连续演示两种读法。
    std::cout << "=== 按词读取 ===\n"
                 "请输入几个单词（输入 end 结束本轮）：" << std::endl;

    std::string word;
    // 每次循环读取一个词；遇到 EOF、非法输入或读到 "end" 时停止
    while (std::cin >> word && word != "end") {
        std::cout << "  读到单词：" << word << std::endl;
    }
    // 读到 "end" 后，输入流仍处于正常状态，但 "end" 所在行的换行符
    // 还留在流里。若直接 getline，会先读到一个空行而误结束。
    // 这里用一个 getline 把当前行剩余内容吃掉，让后面的演示从下一行开始。
    // （若用户用 Ctrl+Z/Ctrl+D 触发 EOF 结束，则先 clear 再尝试。）
    if (!std::cin) {
        std::cin.clear();
    }
    std::string rest;
    std::getline(std::cin, rest);   // 丢弃 "end" 所在行的剩余部分

    // ---------------------------------------------------------------------
    // 二、用 getline 按行读取：保留行内空白，遇到换行结束
    // ---------------------------------------------------------------------
    std::cout << "\n=== 按行读取 ===\n"
                 "请输入几行文字（空行结束）：" << std::endl;

    std::string line;
    while (std::getline(std::cin, line)) {            // 读整行
        if (line.empty()) {                            // 读到空行则结束
            break;
        }
        std::cout << "  读到一行：" << line << std::endl;
    }

    return 0;
}

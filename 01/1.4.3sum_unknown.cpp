// ===========================================================================
//  《C++ Primer》1.4.3 节示例：读取数量未知的输入
// ---------------------------------------------------------------------------
//  while (std::cin >> value)
//    - 输入运算符 >> 返回其左侧的流对象（即 std::cin）。
//    - 当流出现在条件中时，其真假由流的状态决定：
//        流有效（读到合法数据）   → 真
//        遇到文件结束符(EOF)或非法输入 → 假
//
//  如何结束输入（发送 EOF）：
//    - Windows：Ctrl+Z 后回车
//    - Linux/macOS：Ctrl+D
//  在 VS/CLion 调试控制台里输入数据后，按上述组合键即可结束循环。
// ===========================================================================
#include <iostream>

int main()
{
    int sum = 0, value = 0;
    while (std::cin >> value)     // 不断读取，直到 EOF 或遇到非整数输入
        sum += value;
    std::cout << "Sum is " << sum << std::endl;
    return 0;
}

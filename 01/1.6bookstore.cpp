// ===========================================================================
//  《C++ Primer》1.6 节示例：书店程序（第 1 章综合示例）
// ---------------------------------------------------------------------------
//  场景：书店有每笔交易的记录（ISBN 数量 单价）。需要把「同一 ISBN 且连续
//       出现」的多笔交易累加成一条汇总记录后输出；一旦遇到新的 ISBN，
//       就把上一组汇总输出，再开始累加新的一组。
//
//  算法：
//    1. 读入第一条记录到 total（当前正在累加的汇总）。
//    2. 逐条读入 trans：
//         - 若 trans 与 total 同 ISBN → total += trans；
//         - 否则 → 输出 total，让 total = trans（开始新一组）。
//    3. 循环结束后，最后一组 total 还没输出，补上。
//
//  输入示例：
//    0-201-78345-X 3 20.00
//    0-201-78345-X 2 25.00
//    0-201-78346-X 1 10.00
//    0-201-78346-X 4 10.00
//  输出：
//    0-201-78345-X 5 110 22
//    0-201-78346-X 5 50 10
//
//  调试建议：在 if (total.isbn() == trans.isbn()) 处下断点，
//           观察 total 如何随每笔交易累加，以及切换 ISBN 时的输出。
// ===========================================================================
#include <iostream>
#include "Sales_item.h"

int main()
{
    Sales_item total;              // 当前正在累加的汇总记录

    // 读入第一条记录；若有数据才进入处理
    if (std::cin >> total) {
        Sales_item trans;          // 逐笔读入的记录
        while (std::cin >> trans) {
            if (total.isbn() == trans.isbn()) {
                total += trans;    // 同一本书：累加
            } else {
                std::cout << total << std::endl;  // 换书：输出上一组
                total = trans;                     // 开始新一组
            }
        }
        // 输出最后一组（循环结束时仍未输出）
        std::cout << total << std::endl;
    } else {
        std::cerr << "No data?!" << std::endl;     // 没有任何输入
        return -1;
    }

    return 0;
}

// ===========================================================================
//  《C++ Primer》1.4.2 节示例：for 语句（递减版）
// ---------------------------------------------------------------------------
//  演示 for 循环「递减」的用法：从 10 数到 1。
//  注意：
//    - 条件改为 val > 0（用 > 而非 >=，避免与无符号数相关的常见错误）
//    - 递增表达式改为 --val
// ===========================================================================
#include <iostream>

int main()
{
    for (int val = 10; val > 0; --val)
        std::cout << val << " ";  // 依次输出 10 9 8 ... 1
    std::cout << std::endl;       // 最后换行并刷新缓冲
    return 0;
}

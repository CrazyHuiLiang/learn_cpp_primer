// ===========================================================================
//  《C++ Primer》1.5.2 节示例：初识成员函数
// ---------------------------------------------------------------------------
//  功能：读入两条销售记录，仅当它们的 ISBN 相同时才相加并输出；
//       否则在标准错误上提示，并返回非 0 表示失败。
//
//  要点：
//    - item.isbn() 是「成员函数(member function)」调用，点运算符 . 表示
//      「对 item 这个对象调用其 isbn() 成员」，返回它的 ISBN。
//    - isbn() 后面的 const 表示它是一个「常量成员函数」，不修改对象。
//    - 用 cerr 输出错误信息是惯例；返回 -1 让操作系统知道程序异常终止。
//
//  输入示例（ISBN 相同 → 正常相加）：
//    0-201-78345-X 3 20.00
//    0-201-78345-X 2 25.00
//  输入示例（ISBN 不同 → 报错）：
//    0-201-78345-X 3 20.00
//    0-201-99999-9 1 10.00
// ===========================================================================
#include <iostream>
#include "Sales_item.h"

int main()
{
    Sales_item item1, item2;
    std::cin >> item1 >> item2;

    // 用成员函数 isbn() 比较 ISBN
    if (item1.isbn() == item2.isbn()) {
        std::cout << item1 + item2 << std::endl;
        return 0;                  // 正常结束
    } else {
        std::cerr << "Data must refer to same ISBN" << std::endl;
        return -1;                 // 异常结束
    }
}

// ===========================================================================
//  《C++ Primer》1.5.1 节示例：读入并输出一条 Sales_item
// ---------------------------------------------------------------------------
//  Sales_item 类的细节见 include/Sales_item.h。
//  一条销售记录的输入格式为：ISBN 数量 单价
//    例如： 0-201-78345-X 3 20.00
//
//  本程序：从标准输入读入一条记录，再原样输出。
//  注意：>> 和 << 都已由 Sales_item 类「重载」，能直接作用于其对象，
//       用法和内置类型(int 等)完全一致 —— 这正是抽象的好处。
// ===========================================================================
#include <iostream>
#include "Sales_item.h"

int main()
{
    Sales_item book;
    std::cin >> book;             // 读入：ISBN 数量 单价
    std::cout << book << std::endl;  // 输出：ISBN 数量 总额 平均单价
    return 0;
}

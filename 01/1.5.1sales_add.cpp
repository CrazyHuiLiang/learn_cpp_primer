// ===========================================================================
//  《C++ Primer》1.5.1 节示例：两条 Sales_item 相加
// ---------------------------------------------------------------------------
//  功能：读入两条销售记录，输出它们的和。
//
//  输入示例（两行，ISBN 必须相同）：
//    0-201-78345-X 3 20.00
//    0-201-78345-X 2 25.00
//  输出：
//    0-201-78345-X 5 110 22
//    （ISBN 总册数5 总额110 平均单价22）
//
//  说明：operator+ 要求两条记录的 ISBN 相同，它会把册数与总额分别相加。
//       若 ISBN 不同，结果在本章语义下无意义（第 1 章暂不处理该错误）。
// ===========================================================================
#include <iostream>
#include "Sales_item.h"

int main()
{
    Sales_item item1, item2;
    std::cin >> item1 >> item2;   // 连续读入两条记录
    std::cout << item1 + item2 << std::endl;  // 输出两者之和
    return 0;
}

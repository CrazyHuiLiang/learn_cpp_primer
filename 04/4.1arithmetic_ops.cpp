// ===========================================================================
//  《C++ Primer》4.1 节示例：算术运算符
// ---------------------------------------------------------------------------
//  要点：
//    1. 算术运算符：+（正/加）、-（负/减）、*（乘）、/（除）、%（取模）
//    2. 一元正号 +、一元负号 -；二元 + - * / %
//    3. 整数除法「向 0 截断」(truncation toward zero)：丢弃小数部分，
//       即商的绝对值向下取整，符号由分子分母共同决定。
//       例如 7/2 == 3, -7/2 == -3, 7/-2 == -3, -7/-2 == 3。
//    4. 取模 % 仅适用于整型（bool 除外）；满足 (a/b)*b + a%b == a。
//       C++11 起，取模结果的符号由分子的符号决定(向 0 截断下的定义)：
//       -7 % 2 == -1, 7 % -2 == 1, -7 % -2 == -1。
//    5. 运算符优先级与结合律：* / % 高于 + -；同级从左到右结合。
//       可用括号改变求值顺序。
//    6. 除数为 0 是未定义行为(UB)；浮点除以 0 在 IEEE-754 下为 Inf/NaN。
// ===========================================================================
#include <iostream>

int main()
{
    // --- 一元正号 / 负号 ---
    int a = 5;
    std::cout << "一元负号 -a = " << -a << '\n';   // -5
    std::cout << "一元正号 +a = " << +a << '\n';   //  5（少用，主要强调）

    // --- 二元算术 ---
    int x = 17, y = 5;
    std::cout << "x=" << x << ", y=" << y << '\n';
    std::cout << "x + y = " << x + y << '\n';      // 22
    std::cout << "x - y = " << x - y << '\n';      // 12
    std::cout << "x * y = " << x * y << '\n';      // 85
    std::cout << "x / y = " << x / y << '\n';      // 3  （整数除法，截断小数）
    std::cout << "x % y = " << x % y << '\n';      // 2  （17 = 3*5 + 2）

    // --- 整数除法向 0 截断 / 取模符号规则 ---
    std::cout << "\n--- 整数除法与取模的符号 ---\n";
    std::cout << " 7 /  2 = " <<   7 / 2  << ",  7 %  2 = " <<   7 % 2  << '\n'; //  3,  1
    std::cout << "-7 /  2 = " << -7 / 2  << ", -7 %  2 = " << -7 % 2  << '\n'; // -3, -1
    std::cout << " 7 / -2 = " <<   7 / -2 << ",  7 % -2 = " <<   7 % -2 << '\n'; // -3,  1
    std::cout << "-7 / -2 = " << -7 / -2 << ", -7 % -2 = " << -7 % -2 << '\n'; //  3, -1
    // 恒等式验证：(a/b)*b + a%b == a
    // 注意：取模结果的符号跟随分子(被除数)。

    // --- 浮点除法（至少一个操作数是浮点）---
    std::cout << "\n--- 浮点除法 ---\n";
    std::cout << "17.0 / 5 = " << 17.0 / 5 << '\n';   // 3.4
    std::cout << "17   / 5.0 = " << 17   / 5.0 << '\n'; // 3.4

    // --- 优先级与结合律 ---
    std::cout << "\n--- 优先级与结合律 ---\n";
    // * / % 优先级高于 + -；同级从左到右结合
    std::cout << "6 + 3 * 4 / 2 = " << 6 + 3 * 4 / 2 << '\n';
    // 求值过程：3*4=12 → 12/2=6 → 6+6=12
    std::cout << "(6 + 3) * 4 / 2 = " << (6 + 3) * 4 / 2 << '\n'; // 18
    std::cout << "6 + 3 * (4 / 2) = " << 6 + 3 * (4 / 2) << '\n'; // 12

    // 同级从左到右：20 / 5 * 2 => (20/5)*2 = 8，而不是 20/(5*2)=2
    std::cout << "20 / 5 * 2 = " << 20 / 5 * 2 << '\n'; // 8

    // --- 溢出：有符号整型溢出是未定义行为 ---
    std::cout << "\n--- 溢出示意（仅注释，不演示 UB）---\n";
    // int max = 2147483647; max + 1; // <- UB，不要这样写
    std::cout << "（详见注释：有符号整数溢出为 UB，无符号溢出按 2^n 回绕）\n";

    return 0;
}

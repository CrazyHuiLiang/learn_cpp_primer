// ===========================================================================
//  《C++ Primer》4.4 节示例：递增和递减运算符
// ---------------------------------------------------------------------------
//  要点：
//    1. 前置 ++i：先递增 i，再返回「递增后」的值（返回左值）。
//    2. 后置 i++：先保存 i 的旧值，再递增 i，返回「递增前」的旧值（返回右值）。
//       因此：j = ++i; 与 j = i++; 结果不同。
//    3. 前置版本性能略优（无需保存旧值），对迭代器/复杂对象尤其推荐 ++i。
//    4. 经典组合：*pbeg++ 等价于 *(pbeg++)
//       即「取 pbeg 当前所指对象，然后 pbeg 前进一步」。
//       —— 后置 ++ 优先级高于解引用 *，但写成 *(pbeg++) 更清晰。
//    5. 严禁对同一变量在同一表达式内多次修改（如 i = i++ + 1;）——未定义行为。
//    6. 递减 -- 同理，分前置 --i 与后置 i--。
// ===========================================================================
#include <iostream>
#include <vector>

int main()
{
    // --- 前置 vs 后置 ---
    std::cout << "--- 前置 ++ 与后置 ++ ---\n";
    int i = 5;

    int j1 = ++i;            // 先 ++i（i 变 6），再把 6 赋给 j1
    std::cout << "int j1 = ++i;  i=" << i << ", j1=" << j1 << '\n'; // 6, 6

    i = 5;                   // 复位
    int j2 = i++;            // 先取 i 的旧值 5 赋给 j2，再 ++i（i 变 6）
    std::cout << "int j2 = i++;  i=" << i << ", j2=" << j2 << '\n'; // 6, 5

    // 递减同理
    i = 5;
    int k1 = --i;            // i 变 4，k1 = 4
    std::cout << "int k1 = --i;  i=" << i << ", k1=" << k1 << '\n'; // 4, 4

    i = 5;
    int k2 = i--;            // k2 = 5（旧值），i 变 4
    std::cout << "int k2 = i--;  i=" << i << ", k2=" << k2 << '\n'; // 4, 5

    // --- 经典表达式：*pbeg++ ---
    std::cout << "\n--- *pbeg++ 的含义 ---\n";
    std::vector<int> vec = {10, 20, 30, 40, 50};
    auto pbeg = vec.begin();

    // *pbeg++ 等价于 *(pbeg++)
    //   pbeg++：返回 pbeg 的旧值（指向当前元素），同时 pbeg 前进一步
    //   *(旧值)：解引用得到当前元素
    std::cout << "第一项 = " << *pbeg++ << '\n';   // 10，然后 pbeg 指向 20
    std::cout << "第二项 = " << *pbeg++ << '\n';   // 20，然后 pbeg 指向 30
    std::cout << "第三项 = " << *pbeg++ << '\n';   // 30

    // --- 用迭代器逐个输出（循环中常见后置 ++）---
    std::cout << "\n--- 用迭代器逐个输出 ---\n";
    std::cout << "vec = ";
    for (auto it = vec.cbegin(); it != vec.cend(); ++it) {
        std::cout << *it;
        if (it + 1 != vec.cend()) std::cout << ", ";
    }
    std::cout << '\n';

    // 上面的 ++it 也可写 it++，但前置更推荐：
    //   - 前置 ++ 直接修改并返回自身，无需保存旧值；
    //   - 对迭代器这种对象类型，前置版本省去一次拷贝，效率略高；
    //   - 习惯上「前进迭代器」一律用前置 ++。

    // --- 未定义行为警示（仅注释，不演示）---
    // 下列写法均为未定义行为(UB)，不同编译器结果可能不同：
    //   i = i++;          // 同一表达式内两次修改 i
    //   cout << i << " " << i++ << endl;  // 求值顺序未指定
    //   a[i] = i++;       // 同样 UB
    // 原则：一个表达式中，同一变量最多被修改一次，且修改的结果要能被读取顺序确定。

    return 0;
}

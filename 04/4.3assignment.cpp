// ===========================================================================
//  《C++ Primer》4.3 节示例：赋值运算符
// ---------------------------------------------------------------------------
//  要点：
//    1. 赋值运算符 = 是「右结合」的：a = b = c = 0; 等价于 a = (b = (c = 0));
//    2. 赋值运算符返回「左值(lvalue)」—— 指向其左侧对象，故可连续赋值，
//       也可写作 (a = b) = 5;（罕见，但合法）。
//    3. 左值(lvalue)：能取地址、可出现在赋值号左侧的表达式（如变量名、*p、a[i]）。
//       右值(rvalue)：不能取地址、不能被赋值的表达式（如字面值、算术结果）。
//    4. 复合赋值：+= -= *= /= %= 等，等价于 a = a OP b;（a 只求值一次）。
//    5. 常见错误：if (i = 5) 误写——应为 if (i == 5)。
//       = 是赋值，== 是比较。建议把常量写在左边：if (5 == i) 编译器能帮你抓错。
//    6. 赋值两侧类型不同时会发生隐式转换，窄化转换(如 double→int)丢精度。
// ===========================================================================
#include <iostream>

int main()
{
    // --- 赋值是右结合、返回左值 ---
    std::cout << "--- 右结合：连续赋值 ---\n";
    int a = 0, b = 0, c = 0;
    a = b = c = 42;            // 等价于 a = (b = (c = 42));
    std::cout << "a=" << a << " b=" << b << " c=" << c << '\n'; // 42 42 42

    // 链式赋值的求值方向：最右侧 c = 42 先求值，其结果(左值 c)再赋给 b，依此类推。
    // 这正是「右结合」的体现。

    // --- 左值 vs 右值 ---
    std::cout << "\n--- 左值 vs 右值 ---\n";
    int x = 10;                // x 是左值；10 是右值（字面值）
    int* p = &x;               // &x 取地址，要求 x 是左值
    *p = 20;                   // *p 是左值（解引用结果是左值，可被赋值）
    std::cout << "x = " << x << '\n';   // 20
    // 10 = x;                  // 错误：10 是右值，不能被赋值
    // x + 1 = 5;               // 错误：x+1 是右值

    // --- 复合赋值运算符 ---
    std::cout << "\n--- 复合赋值 ---\n";
    int n = 100;
    n += 5;  std::cout << "n += 5  -> " << n << '\n';   // 105
    n -= 10; std::cout << "n -= 10 -> " << n << '\n';   // 95
    n *= 2;  std::cout << "n *= 2  -> " << n << '\n';   // 190
    n /= 3;  std::cout << "n /= 3  -> " << n << '\n';   // 63  （整数除法截断）
    n %= 10; std::cout << "n %= 10 -> " << n << '\n';   // 3
    // 等价于 n = n OP expr，但 n 只求值一次（n 为复杂表达式时有意义）

    // --- 常见错误：= 与 == 混淆 ---
    std::cout << "\n--- 常见错误警示：= 与 == ---\n";
    int i = 0;
    // ！！！危险写法！！！
    // if (i = 5) {  ...  }   // 这是「赋值」，不是「比较」！
    //   含义：把 5 赋给 i，再用 i(=5,非零) 作为条件 → 恒为真。
    //   几乎可以肯定这是把 == 误写成 = 的笔误，编译器通常会给警告。
    // 正确写法：if (i == 5)
    i = 0;
    if (i == 5) {                                   // 正确的比较
        std::cout << "i 等于 5（不会执行本分支）\n";
    } else {
        std::cout << "i 不等于 5，i = " << i << '\n';
    }

    // 防御性写法：常量放左边，误写成 = 时编译器直接报错
    // if (5 = i)  ...   // 编译错误：5 不能被赋值，帮你立刻发现问题
    if (5 == i) {
        std::cout << "(防御写法) 5 == i 成立\n";
    } else {
        std::cout << "(防御写法) 5 == i 不成立，i = " << i << '\n';
    }

    // --- 隐式（窄化）转换 ---
    std::cout << "\n--- 赋值时的隐式转换 ---\n";
    int  m = 3.14;            // double → int，小数部分被截断（窄化，有警告风险）
    double d = m;             // int → double，安全提升
    std::cout << "int m = 3.14; -> m = " << m << '\n';   // 3
    std::cout << "double d = m; -> d = " << d << '\n';   // 3

    return 0;
}

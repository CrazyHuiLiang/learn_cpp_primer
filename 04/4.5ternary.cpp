// ===========================================================================
//  《C++ Primer》4.5 节示例：条件运算符（三目运算符 ? :）
// ---------------------------------------------------------------------------
//  要点：
//    1. 语法：cond ? expr1 : expr2
//       cond 为真 → 整个表达式的值为 expr1；否则为 expr2。
//    2. 条件运算符是「右结合」的，故可嵌套：
//       a ? b : c ? d : e  等价于  a ? b : (c ? d : e)
//    3. 嵌套条件运算符可用来在表达式里写简单的「多分支选择」，
//       例如求三个数中的最大值。但层数过多会损害可读性，建议改用 if-else。
//    4. 当 expr1 与 expr2 都是左值且类型相同时，条件运算符的结果也是左值，
//       可以出现在赋值号左侧（作左值使用）——
//       但需两侧同类型；若类型不同则发生转换，通常退化为右值。
//    5. 条件运算符的优先级很低，仅次于赋值与逗号；输出流中要用括号括起来。
// ===========================================================================
#include <iostream>

int main()
{
    // --- 基本用法 ---
    std::cout << "--- 基本用法：取较大值 ---\n";
    int a = 3, b = 7;
    int max_ab = (a > b) ? a : b;
    std::cout << "max(" << a << ", " << b << ") = " << max_ab << '\n'; // 7

    // --- 嵌套条件运算符：求三个数中的最大值 ---
    std::cout << "\n--- 嵌套：三数取最大 ---\n";
    int x = 12, y = 9, z = 15;
    // 条件运算符右结合，可写为：
    //   x > y ? x : y   先得 x、y 的较大者；再与 z 比较
    int max_xyz = (x > y ? x : y) > z ? (x > y ? x : y) : z;
    std::cout << "max(" << x << "," << y << "," << z << ") = " << max_xyz << '\n'; // 15

    // 上面写法重复了一次 (x>y?x:y)，可读性一般。更常见的等价嵌套写法：
    //   x >= y ? (x >= z ? x : z)
    //          : (y >= z ? y : z)
    int max_xyz2 = (x >= y) ? (x >= z ? x : z)
                            : (y >= z ? y : z);
    std::cout << "max_xyz2 = " << max_xyz2 << '\n'; // 15
    // 提示：三目嵌套层数一多就难读，生产代码建议直接用 if-else 或 std::max。

    // --- 条件运算符的优先级：输出时务必加括号 ---
    std::cout << "\n--- 优先级：输出时要加括号 ---\n";
    int grade = 75;
    // 下面这行若不加外层括号，会因 << 优先级高于 ?: 而编译失败/语义错误
    std::cout << "成绩判定: " << (grade >= 60 ? "及格" : "不及格") << '\n';

    // --- 条件运算符作左值（两侧均为同类型左值时）---
    std::cout << "\n--- 条件运算符作左值 ---\n";
    int low = 0, high = 0;
    bool raise_high = true;     // 决定给谁加 1
    // (cond ? lval1 : lval2) = 5;  两侧都是 int 左值，结果也是左值
    (raise_high ? high : low) = 5;
    std::cout << "raise_high=true  -> low=" << low << ", high=" << high << '\n'; // 0, 5

    raise_high = false;
    (raise_high ? high : low) = 9;
    std::cout << "raise_high=false -> low=" << low << ", high=" << high << '\n'; // 9, 5

    // 注意：若两侧类型不同（如 int 与 double），条件运算符会做类型转换，
    //       结果通常退化为右值，不能再被赋值。
    //   int m = 1; double d = 2.0;
    //   (cond ? m : d) = 3;   // 编译错误：结果是右值

    return 0;
}

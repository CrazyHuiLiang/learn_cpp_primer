// ===========================================================================
//  《C++ Primer》5.6 节示例：break 与 continue
// ---------------------------------------------------------------------------
//  本程序：
//    1. 用 break 演示「找第一个能被 7 整除的三位数」——一旦找到就跳出循环。
//    2. 用 continue 演示「只累加正数，跳过负数」——遇到负数跳过本次剩余语句。
//
//  要点：
//    1. break：跳出「最近的」循环（for/while/do-while）或 switch 语句。
//       只影响最内层结构，嵌套循环时不会一次跳出多层。
//    2. continue：终止「本次」循环体的剩余语句，直接进入下一轮循环：
//         - 在 while/do-while 中，跳到条件判断；
//         - 在 for 中，跳到 expression（如 ++i）再判断 condition。
//       continue 同样只作用于最内层循环。
//    3. break / continue 都不应滥用；过度使用会损害可读性，
//       但在「提前结束」或「跳过个别情况」时很自然。
// ===========================================================================
#include <iostream>

int main()
{
    // ---------- 1. break：找第一个能被 7 整除的三位数 ----------
    // 从 100 开始向上找，找到第一个就 break 跳出循环
    int firstBy7 = -1;
    for (int i = 100; i < 1000; ++i) {
        if (i % 7 == 0) {
            firstBy7 = i;
            break;                 // 找到即跳出 for，不再继续遍历
        }
    }
    std::cout << "第一个能被 7 整除的三位数是：" << firstBy7 << std::endl;

    // ---------- 2. continue：只累加正数，跳过负数 ----------
    const int data[] = {3, -1, 5, -2, 8, -4, 7};
    int positiveSum = 0;
    for (int x : data) {           // 范围 for 遍历数组
        if (x < 0) {
            continue;              // 负数：跳过本次剩余语句，直接取下一个元素
            // 在范围 for 中，continue 相当于跳到 ++it 再判断 it != end
        }
        positiveSum += x;          // 只有正数才会执行到这一行
    }
    std::cout << "正数之和 = " << positiveSum << std::endl;
    // 期望：3 + 5 + 8 + 7 = 23

    return 0;
}

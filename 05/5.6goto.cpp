// ===========================================================================
//  《C++ Primer》5.6 节示例：goto 语句（仅作了解，强烈建议避免使用）
// ---------------------------------------------------------------------------
//  本程序：用一个极简示例演示 goto 的语法。
//
//  要点：
//    1. goto 的形式：
//         goto label;
//       其中 label 是同一函数内某条语句前的「带冒号标识符」：
//         label: some_statement;
//    2. goto 只能跳转到同一函数内的标签；不能跨函数。
//    3. goto 不能向前跳过「带初始化的变量定义」，否则编译报错
//       （因为变量在使用时尚未初始化）。
//    4. 强烈建议：不要使用 goto！
//       - 它会破坏结构化控制流，使代码难以阅读和维护；
//       - 任何能用 goto 实现的逻辑，都可以用 if/while/for/break/continue
//         更清晰地表达；
//       - 历史上 goto 被认为是「有害的」(Dijkstra, 1968)。
//       现代 C++ 中几乎不再使用 goto，这里仅为「了解语法」而演示。
// ===========================================================================
#include <iostream>

int main()
{
    std::cout << "演示 goto 语句（仅作了解，生产代码请勿使用）" << std::endl;

    int i = 0;

    // 用 goto 模拟一个循环 —— 但请用 while/for 替代，这里只为演示语法
loop_start:                       // 标签：以标识符加冒号定义
    if (i < 3) {
        std::cout << "  i = " << i << "（用 goto 跳回 loop_start）" << std::endl;
        ++i;
        goto loop_start;          // 跳回标签 loop_start 处继续执行
    }
    // 当 i == 3 时条件为假，自然向下执行

    std::cout << "goto 演示结束。请记住：不要在生产代码里用 goto！" << std::endl;

    // ---------- 等价的结构化写法（推荐） ----------
    // 上面这段 goto 逻辑等价于下面这个普通 while 循环：
    //   int j = 0;
    //   while (j < 3) {
    //       std::cout << "  j = " << j << std::endl;
    //       ++j;
    //   }

    return 0;
}

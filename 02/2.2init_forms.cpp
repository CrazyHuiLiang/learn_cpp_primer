// ===========================================================================
//  《C++ Primer》2.2 节示例：变量初始化的多种形式
// ---------------------------------------------------------------------------
//  要点：
//    1. C++ 有四种初始化形式：
//         - 默认初始化：不显式给初值，内置类型在函数体内是不确定的（危险！），
//                       类类型由默认构造函数决定。
//         - 拷贝初始化：用等号 `=`，把右侧值「拷贝」到新对象中。
//         - 直接初始化：用圆括号 `()`，直接构造对象。
//         - 列表初始化：用花括号 `{}`（C++11 起统一推荐的形式）。
//    2. 【列表初始化的杀手锏】禁止「窄化(narrowing)」：
//         用 {} 初始化时，若初始值可能丢失信息（如 double→int、大整数→小类型），
//         编译器会报错，比 = 和 () 更安全。
//    3. 「初始化」与「赋值」是两回事：
//         - 初始化：对象创建时就赋予初值（构造阶段）。
//         - 赋值  ：对象已存在，用新值替换旧值（operator=）���
//
//  说明：本文件不写出会编译失败的代码，而是在注释里说明哪些窄化会被禁止。
// ===========================================================================
#include <iostream>

int main()
{
    // ---- 1. 默认初始化 ----
    // 函数体内的内置类型默认初始化 = 不确定值（未定义行为风险），
    // 务必显式初始化！全局作用域的内置类型才会默认初始化为 0。
    int a;              // 危险：值未定义，不要这么用
    int b = 0;          // 好习惯：显式给初值
    std::cout << "b = " << b << "\n";
    (void)a;            // 避免未使用变量警告，但不读取它的值

    // ---- 2. 拷贝初始化（=）----
    int c = 10;         // 等号：拷贝初始化
    double d = 3.14;
    std::cout << "c = " << c << ", d = " << d << "\n";

    // ---- 3. 直接初始化（()）----
    int e(20);          // 圆括号：直接初始化
    double f(2.718);
    std::cout << "e = " << e << ", f = " << f << "\n";

    // ---- 4. 列表初始化（{}）—— 推荐形式 ----
    int g{30};          // 花括号：列表初始化
    double h{1.414};
    std::cout << "g = " << g << ", h = " << h << "\n";

    // 也可写成 = {} 形式，效果与 {} 相同（仍是列表初始化）
    int m = {40};
    std::cout << "m = " << m << "\n\n";

    // ---- 5. 列表初始化禁止窄化（这是它最大的优势）----
    // 下面这些「合法但危险」的转换，用 = 或 () 不会报错，但用 {} 会报错：
    //
    //   int x = 3.14;     // 拷贝初始化：能编译，但 3.14 被截断为 3（信息丢失）
    //   int y(3.14);      // 直接初始化：同上，能编译但有截断
    //   int z{3.14};      // 列表初始化：编译错误！double→int 是窄化转换
    //
    //   char ch = 300;    // 能编译，但 300 超出 char 范围，被截断
    //   char ch2{300};    // 编译错误！常量 300 不在 char 表示范围内
    //
    // 结论：当你想「用初值精确构造对象、不容忍精度丢失」时，优先用 {}。

    // 用浮点字面值初始化整型时，{} 会拒绝；但用同类型或更宽类型则没问题：
    double pi = 3.14159;
    double pi2{pi};        // OK：double→double，无窄化
    (void)pi2;             // 仅作演示，避免未使用变量警告
    // int n{pi};           // 错误：double→int 窄化
    int n = static_cast<int>(pi);  // 显式转换是合法的，因为「你」要为截断负责
    std::cout << "pi = " << pi << ", n = " << n << "\n\n";

    // ---- 6. 初始化 vs 赋值 ----
    int v = 5;            // 这是「初始化」（创建 v 并赋初值）
    v = 8;                // 这是「赋值」（v 已存在，覆盖旧值）
    std::cout << "v = " << v << "\n";
    // 区别的意义：const 对象、引用等只能初始化、不能赋值。

    return 0;
}

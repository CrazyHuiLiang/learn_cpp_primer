// ===========================================================================
//  《C++ Primer》2.3 节示例：指针（pointer）
// ---------------------------------------------------------------------------
//  要点：
//    1. 指针存放某个对象的「地址」。用取地址符 & 取得对象地址，
//       用解引用符 * 间接访问指针所指对象。
//    2. 空指针用 nullptr（C++11）表示，不指向任何对象。
//    3. 指针本身是一个变量，可以被重新赋值（指向别的对象）；这与引用不同
//       （引用一经绑定不可更改）。
//    4. 指针可以指向指针（多级指针），书写时注意 * 的结合方式。
//    5. 【易错点】解引用与赋值的优先级：
//         *p = 5;   // 把 5 赋给 p 所指对象
//         p  = &x;  // 让 p 指向 x（改变的是指针本身，不是所指对象）
//       初学者常混淆 *p = 与 p =，务必看清「= 左侧有没有 *」。
//
//  本程序：演示取地址、解引用、空指针、指针重指向、多级指针。
// ===========================================================================
#include <iostream>

int main()
{
    //system("chcp 65001 > nul");  // 切换控制台代码页到 UTF-8，并屏蔽输出

    // ---- 1. 取地址 & 与解引用 * ----
    int ival = 42;
    int *pi = &ival;       // pi 存放 ival 的地址（pi 是「指向 int 的指针」）
    std::cout << "ival     = " << ival << "\n";
    std::cout << "&ival    = " << &ival << "\n";
    std::cout << "pi       = " << pi << "\n";
    std::cout << "*pi      = " << *pi << "\n";   // 解引用：取出 pi 所指对象

    // 通过解引用修改原对象
    *pi = 100;             // 等价于 ival = 100
    std::cout << "after *pi=100: ival = " << ival << "\n\n";

    // ---- 2. 空指针 nullptr ----
    int *p1 = nullptr;     // C++11 推荐写法，不指向任何对象
    // int *p2 = NULL;     // 旧写法，建议改用 nullptr
    // int *p3 = 0;        // 也合法，但可读性差
    std::cout << "p1 (nullptr) = " << p1 << "\n";
    if (p1 == nullptr)     // 判空的标准做法
        std::cout << "p1 不指向任何对象\n\n";
    // *p1 = 5;            // 错误！解引用空指针是未定义行为

    // ---- 3. 指针赋值与重指向 ----
    int a = 10, b = 20;
    int *p = &a;           // p 指向 a
    std::cout << "*p = " << *p << " (指向 a)\n";
    p = &b;                // 让 p 改指向 b（注意：没有 *，改的是指针本身）
    std::cout << "*p = " << *p << " (改指向 b)\n";
    *p = 30;               // 有 *：修改 p 所指对象（即 b）
    std::cout << "b = " << b << " (通过 *p 修改了 b)\n\n";

    // ---- 4. 【易错】解引用 vs 指针赋值，看清楚 = 左侧有没有 * ----
    int x = 1, y = 9;
    int *q = &x;
    *q = y;                // 把 y 的值赋给 q 所指对象(x)，x 变 9，q 仍指向 x
    std::cout << "after *q=y:  x = " << x << ", q 指向 " << q << "\n";
    q  = &y;               // 让 q 指向 y（不改任何变量的值，只改 q 自己）
    std::cout << "after q=&y:  q 指向 " << q << ", y 地址 = " << &y << "\n\n";

    // ---- 5. 指向指针的指针 ----
    int  val  = 7;
    int *pval = &val;      // 一级指针：指向 int
    int **pp  = &pval;     // 二级指针：指向「int 的指针」
    std::cout << "val   = " << val << "\n";
    std::cout << "*pval = " << *pval << "   (解一次：得到 int)\n";
    std::cout << "**pp  = " << **pp  << "   (解两次：先得指针，再得 int)\n";
    // 通过二级指针间接修改最底层变量
    **pp = 88;             // 等价于 val = 88
    std::cout << "after **pp=88: val = " << val << "\n";

    return 0;
}

// ===========================================================================
//  《C++ Primer》2.3 节示例：引用（reference / 左值引用）
// ---------------------------------------------------------------------------
//  要点：
//    1. 引用是某个对象的「别名」：定义引用时必须「立即绑定」到一个对象，
//       且此后不能再绑定到其它对象（「从一而终」）。
//    2. 对引用做的所有操作，实际上都作用在它所绑定的对象上。
//    3. 引用必须初始化（不能用未初始化的引用）；定义引用时绑定的对象必须
//       类型严格匹配（且通常要求是「左值」）。
//    4. 引用作为函数形参时，函数内对形参的修改会反映到实参上——这是引用
//       最常见的用途：避免拷贝、实现「输出参数」。
//
//  本程序：演示引用的定义、绑定、别名性质、不可重绑定，并用 exchange()
//  展示引用形参。
// ===========================================================================
#include <iostream>

// 用引用形参交换两个 int：形参 r1/r2 是实参的别名，修改它们即修改实参。
// 对比：若形参写成 int（值传递），交换的只是副本，实参不变。
void exchange(int &r1, int &r2)
{
    int tmp = r1;
    r1 = r2;
    r2 = tmp;
}

int main()
{
    // ---- 1. 定义引用并绑定 ----
    int  val = 42;
    int &ref = val;        // ref 是 val 的别名（类型是「int 的引用」）
    std::cout << "val = " << val << ", ref = " << ref << "\n";

    // ---- 2. 引用是别名：对引用赋值即对原变量赋值 ----
    ref = 100;             // 不是「让 ref 绑定到 100」，而是把 val 改成 100
    std::cout << "after ref=100: val = " << val << "\n";
    // 同理，对引用取地址得到的也是原对象的地址
    std::cout << "&val = " << &val << ", &ref = " << &ref << "\n\n";

    // ---- 3. 引用本身不再绑定到其它对象 ----
    int val2 = 7;
    ref = val2;            // 注意！这是「赋值」不是「重新绑定」
    // 执行后 val（ref 绑定的原对象）变成 7，ref 仍绑定 val，与 val2 无关。
    std::cout << "after ref=val2(7): val = " << val
              << ", val2 = " << val2 << ", ref = " << ref << "\n";
    std::cout << "&val = " << &val << ", &val2 = " << &val2
              << " (ref 仍与 val 同地址)\n\n";

    // ---- 4. 引用必须初始化 ----
    // int &bad;            // 错误：引用必须初始化
    int &ok = val;         // 正确：定义时立即绑定
    (void)ok;

    // ---- 5. 用引用形参交换两个变量 ----
    int x = 1, y = 2;
    std::cout << "before exchange: x = " << x << ", y = " << y << "\n";
    exchange(x, y);        // x、y 真正被交换
    std::cout << "after  exchange: x = " << x << ", y = " << y << "\n";

    return 0;
}

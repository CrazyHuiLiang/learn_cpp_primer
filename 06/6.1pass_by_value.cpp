// ===========================================================================
//  《C++ Primer》6.1 节示例：值传递（pass by value）
// ---------------------------------------------------------------------------
//  要点：
//    - 值传递时，形参(parameter)是实参(argument)的一份拷贝。
//    - 函数内对形参的修改不会影响调用处的实参。
//    - 适合小对象（int、指针等）；对大对象值传递会带来拷贝开销。
//
//  本程序：用 reset(int i) 演示值传递——函数内把 i 置 0，
//  但调用处的原变量不受影响，借此对比说明值传递的语义。
// ===========================================================================
#include <iostream>

// 值传递：i 是实参的拷贝，修改 i 不影响外部变量
void reset(int i)
{
    i = 0;   // 仅修改局部拷贝
}

int main()
{
    int n = 42;
    std::cout << "before reset: n = " << n << std::endl;   // 42

    reset(n);   // 值传递：n 的拷贝传入，n 本身不变

    std::cout << "after  reset: n = " << n << std::endl;   // 仍是 42
    return 0;
}

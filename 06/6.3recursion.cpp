//  《C++ Primer》6.3 节示例：递归
// ---------------------------------------------------------------------------
//  要点：
//    - 递归函数直接或间接调用自身。
//    - 递归必须有一个（或多个）终止条件（base case），否则会无限递归直至
//      栈溢出；每层递归向终止条件逼近。
//    - 递归用于阶乘、斐波那契、树形结构遍历等分治问题。
//
//  本程序：实现阶乘 factorial(int n)，演示终止条件 n==1 与递推 n*factorial(n-1)。
// ===========================================================================
#include <iostream>
#include <stdexcept>

// 阶乘：n! = n * (n-1)!，终止条件 1! = 1
int factorial(int n)
{
    if (n < 0) {
        throw std::invalid_argument("factorial: n must be non-negative");
    }
    if (n == 0 || n == 1) {   // 终止条件：0! = 1! = 1
        return 1;
    }
    return n * factorial(n - 1);   // 递推：向 n==1 逼近
}

int main()
{
    for (int i = 0; i <= 6; ++i) {
        std::cout << i << "! = " << factorial(i) << std::endl;
    }
    return 0;
}

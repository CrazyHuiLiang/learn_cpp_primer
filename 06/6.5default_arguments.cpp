// ===========================================================================
//  《C++ Primer》6.5 节示例：默认实参
// ---------------------------------------------------------------------------
//  要点：
//    - 函数声明的某些形参可带默认值；调用时若省略对应实参，则用默认值。
//    - 默认实参只能从右到左连续省略：某个形参有默认值，则其右侧所有形参
//      都必须有默认值。
//    - 默认实参通常在头文件中（且只）声明一次；定义处不再重复默认值。
//    - 调用时实参按位置匹配，不能跳过中间参数只给后面的。
//
//  本程序：window(title, width=80, height=25) 演示默认实参。
// ===========================================================================
#include <iostream>
#include <string>

// 默认实参：从右到左依次给默认值
// 调用时可省略尾部实参：window("w"); window("w", 100); window("w", 100, 50);
void window(const std::string &title, int width = 80, int height = 25)
{
    std::cout << "window(\"" << title << "\", " << width << ", " << height << ")"
              << std::endl;
}

int main()
{
    window("full");        // 用 width=80,  height=25
    window("wide", 100);   // 用 height=25
    window("custom", 100, 50);
    // window("x", , 50);  // 错误：不能跳过 width 只给 height
    return 0;
}

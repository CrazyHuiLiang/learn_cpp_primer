// ===========================================================================
//  《C++ Primer》6.2 节示例：尽量使用 const 引用形参
// ---------------------------------------------------------------------------
//  要点：
//    - const 引用形参能接受：const 对象、字面值、临时对象（右值）。
//      非 const 引用形参无法绑定到这三者，会限制调用方式。
//    - 「能接受字面值」的原因：const 引用可以绑定到右值（包括字面值产生的
//      临时对象），编译器允许把右值隐式转换为一个临时 const 对象再绑定；
//      而 nonconst 引用不能绑定到右值，故无法接受字面值。
//    - 顶层 const 与底层 const 对重载的影响：
//        * 顶层 const（对象本身是 const）不构成重载：int 与 const int 作
//          形参等价，重复定义会报错。
//        * 底层 const（指向/引用的对象是 const）构成重载：
//          f(int&) 与 f(const int&) 是两个不同函数。
//
//  本程序演示：常量、字面值、临时对象都只能传给 const 引用版本；
//  非 const 对象优先匹配非 const 引用版本。
// ===========================================================================
#include <iostream>

// 重载：按是否带底层 const 区分
void f(int &i)              { std::cout << "f(int&)        : " << i << std::endl; }
void f(const int &i)        { std::cout << "f(const int&)  : " << i << std::endl; }

int main()
{
    int        a = 10;   // 非 const 左值
    const int  b = 20;   // const 左值

    f(a);    // a 非 const，精确匹配 f(int&)
    f(b);    // b 是 const，只能匹配 f(const int&)
    f(30);   // 30 是字面值（右值），只能匹配 f(const int&)
    f(a + 1);// 临时对象（右值），只能匹配 f(const int&)

    // 注：若写成 void g(int &i) 然后调用 g(30)，编译失败——
    // 非 const 引用不能绑定到字面值/右值。这就是「尽量用 const 引用」的原因。
    return 0;
}
